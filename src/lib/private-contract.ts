import type { CreateCloudTargetInput } from "@/types/cloud-target";

function record(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

export function parsePrivateContract(text: string, projectId: string): CreateCloudTargetInput {
  const parsed: unknown = JSON.parse(text);
  const root = record(parsed) && record(parsed.cnp_cd_contract) ? parsed.cnp_cd_contract : parsed;
  if (!record(root) || !record(root.cloud_target) || !record(root.kubeconfig_strategy) || !record(root.deployment_defaults)) {
    throw new Error("The contract must contain cloud_target, kubeconfig_strategy and deployment_defaults.");
  }
  const target = root.cloud_target;
  if (target.provider !== "private" || target.cluster_type !== "k3s") {
    throw new Error("Import a private / k3s contract generated by the demo setup.");
  }
  if (!/^[a-f0-9-]{36}$/i.test(projectId) || target.namespace !== `cnp-${projectId.replace(/-/g, "").toLowerCase()}`) {
    throw new Error("The namespace does not match the selected CNP project.");
  }
  if (root.kubeconfig_strategy.mode !== "in_cluster" || root.deployment_defaults.service_type !== "ClusterIP") {
    throw new Error("Private contracts require in_cluster authentication and ClusterIP services.");
  }
  if (root.secret_values && (!record(root.secret_values) || Object.keys(root.secret_values).length > 0)) {
    throw new Error("Upload the observer credential separately; do not include secrets in the contract.");
  }
  // The API validates all provider-specific configuration and enforces authorization.
  return {
    cloud_target: root.cloud_target,
    kubeconfig_strategy: root.kubeconfig_strategy,
    deployment_defaults: root.deployment_defaults,
  } as unknown as CreateCloudTargetInput;
}
